/**
 * QA page (browser side). Renders the real <Short> composition with @remotion/player's Thumbnail at a
 * chosen frame, then measures:
 *  - every overlay text block in the DOM (real fonts, real layout, transforms included),
 *  - every character (Jake / Hoot, found through the QA-only shims) in the live three.js scene:
 *    projected silhouette points, what hides them (raycasts), face points, hands + held objects,
 *    and penetration into the furniture boxes the scene's optional `qa` export declares.
 * The Node side (check.mjs) turns these measurements into problems.
 */
