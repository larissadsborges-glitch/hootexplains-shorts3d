const raf = () => new Promise<void>((r) => requestAnimationFrame(() => r()));

/** Show a frame and wait until React committed it and R3F rendered the matching camera pose. */
Q.goto = async (frame: number, draw = false) => {
  Q.draw = draw;
  Q.setFrame(frame);
  const pose = S.pose(timings, T, frame / FPS);
  let ok = false;
  for (let i = 0; i < 200; i++) {
    await raf();
    const cam = Q.camera as THREE.PerspectiveCamera | null;
    if (Q.committed !== frame || !cam) continue;
    const d = cam.position.distanceTo(new THREE.Vector3(...pose.pos));
    if (d < 1e-4 && Math.abs(cam.fov - pose.fov) < 1e-3 && Q.renders - Q.rendersAtCommit >= (draw ? 3 : 2)) { ok = true; break; }
  }
  if (draw) { await raf(); await raf(); }
  return ok;
};

// ------------------------------------------------------------------ overlays (DOM)
const alpha = (c: string) => {
  if (!c || c === 'transparent') return 0;
  const m = c.match(/rgba?\(([^)]+)\)/);
  if (!m) return 1;
  const p = m[1].split(',').map((s) => parseFloat(s));
  return p.length > 3 ? p[3] : 1;
};
const ownVisual = (el: Element, cs: CSSStyleDeclaration) => {
  if (el.tagName === 'IMG') return true;
  if (alpha(cs.backgroundColor) > 0.05 || (cs.backgroundImage && cs.backgroundImage !== 'none')) return true;
  if (parseFloat(cs.borderTopWidth) > 0 && alpha(cs.borderTopColor) > 0.05 && cs.borderTopStyle !== 'none') return true;
  for (const n of Array.from(el.childNodes)) if (n.nodeType === 3 && n.textContent!.trim()) return true;
  return false;
};
const union = (a: Box | null, r: { left: number; top: number; width: number; height: number }): Box | null => {
  if (r.width <= 0.5 || r.height <= 0.5) return a;
  if (!a) return { x: r.left, y: r.top, w: r.width, h: r.height };
  const x0 = Math.min(a.x, r.left), y0 = Math.min(a.y, r.top);
  const x1 = Math.max(a.x + a.w, r.left + r.width), y1 = Math.max(a.y + a.h, r.top + r.height);
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 };
};
let parentIds = new WeakMap<Element, number>(), nextPid = 1;
const pid = (el: Element) => { if (!parentIds.has(el)) parentIds.set(el, nextPid++); return parentIds.get(el)!; };

const measureOverlays = () => {
  const root = document.querySelector('#qa-root')!;
  const origin = root.getBoundingClientRect();
  const items: any[] = [];
  const visit = (el: Element, opacity: number) => {
    if (el.id === 'qa-annot' || el.tagName === 'CANVAS' || el.tagName === 'AUDIO' || el.tagName === 'VIDEO') return;
    if (el.querySelector(':scope > canvas')) return;
    const cs = getComputedStyle(el);
    if (cs.display === 'none' || cs.visibility === 'hidden') return;
    const op = opacity * parseFloat(cs.opacity || '1');
    if (op < 0.02) return;
    const er = el.getBoundingClientRect();
    const fullFrame = er.width >= 0.9 * W && er.height >= 0.9 * H; // backgrounds / layout layers, never an overlay block
    if (fullFrame || !ownVisual(el, cs)) { for (const c of Array.from(el.children)) visit(c, op); return; }
    const text = ((el as HTMLElement).innerText ?? el.textContent ?? '').replace(/\s+/g, ' ').trim();
    const hasImg = el.tagName === 'IMG' || !!el.querySelector('img');
    if (!text && !hasImg) return; // pure decoration (tints, eyelid bars)
    // tight box: text ink lines + every descendant that paints a background/border/image
    let box: Box | null = null;
    let fontSize = 0;
    const walk = (e: Element) => {
      const c = getComputedStyle(e);
      if (c.display === 'none') return;
      if (e !== el && e.tagName !== 'svg' && ownVisual(e, c) && (alpha(c.backgroundColor) > 0.05 || e.tagName === 'IMG' || parseFloat(c.borderTopWidth) > 0)) box = union(box, e.getBoundingClientRect());
      for (const n of Array.from(e.childNodes)) {
        if (n.nodeType === 3 && n.textContent!.trim()) {
          const rg = document.createRange(); rg.selectNodeContents(n);
          for (const r of Array.from(rg.getClientRects())) box = union(box, r);
          fontSize = Math.max(fontSize, parseFloat(c.fontSize));
        } else if (n.nodeType === 1 && (n as Element).tagName !== 'svg') walk(n as Element);
      }
    };
    if (alpha(cs.backgroundColor) > 0.05 || el.tagName === 'IMG' || parseFloat(cs.borderTopWidth) > 0) box = union(box, el.getBoundingClientRect());
    walk(el);
    if (!box) return;
    const b = box as Box;
    items.push({ text, hasImg, fontSize, opacity: +op.toFixed(2), parent: pid(el.parentElement!), box: { x: Math.round(b.x - origin.left), y: Math.round(b.y - origin.top), w: Math.round(b.w), h: Math.round(b.h) } });
  };
  visit(root, 1);
  return items;
};

// ------------------------------------------------------------------ 3D
const v = new THREE.Vector3();
const visibleChain = (o: THREE.Object3D) => { for (let p: THREE.Object3D | null = o; p; p = p.parent) if (!p.visible) return false; return true; };
const meshesOf = (o: THREE.Object3D) => { const out: THREE.Mesh[] = []; o.traverse((c) => { if ((c as THREE.Mesh).isMesh && visibleChain(c)) out.push(c as THREE.Mesh); }); return out; };
const isUnder = (o: THREE.Object3D, anc: THREE.Object3D) => { for (let p: THREE.Object3D | null = o; p; p = p.parent) if (p === anc) return true; return false; };
const mat = (m: THREE.Mesh) => (Array.isArray(m.material) ? m.material[0] : m.material) as THREE.MeshStandardMaterial;
const params = (m: THREE.Mesh) => ((m.geometry as any).parameters ?? {}) as Record<string, number>;
const near = (a: number | undefined, b: number) => a !== undefined && Math.abs(a - b) < 1e-4;

const project = (cam: THREE.PerspectiveCamera, p: THREE.Vector3) => {
  const q = p.clone().applyMatrix4(cam.matrixWorldInverse);
  const behind = q.z > -cam.near;
  const n = p.clone().project(cam);
  return { x: ((n.x + 1) / 2) * W, y: ((1 - n.y) / 2) * H, behind };
};

const describe = (m: THREE.Mesh, furniture: any[]) => {
  const char = (() => { for (let p: THREE.Object3D | null = m; p; p = p.parent) if (p.userData?.qaChar) return p.userData.qaChar as string; return null; })();
  if (char) return char;
  m.geometry.computeBoundingBox();
  const c = m.geometry.boundingBox!.getCenter(new THREE.Vector3()).applyMatrix4(m.matrixWorld);
  for (const f of furniture) if (c.x >= f.min[0] - 0.02 && c.x <= f.max[0] + 0.02 && c.y >= f.min[1] - 0.02 && c.y <= f.max[1] + 0.02 && c.z >= f.min[2] - 0.02 && c.z <= f.max[2] + 0.02) return f.name;
  const col = mat(m)?.color ? '#' + mat(m).color.getHexString() : '';
  return `${m.geometry.type.replace('Geometry', '').toLowerCase()} ${col} at (${c.x.toFixed(2)}, ${c.y.toFixed(2)}, ${c.z.toFixed(2)})`;
};

type Pt = { w: THREE.Vector3; part: string; face: boolean; mesh: THREE.Mesh };

/** All world-space vertices of a character, tagged with a body-part name and a face flag. */
const characterPoints = (root: THREE.Object3D, kind: string) => {
  const meshes = meshesOf(root);
  const inv = root.matrixWorld.clone().invert();
  let head: THREE.Object3D | null = null;
  const hands: THREE.Mesh[] = [];
  if (kind === 'jake') {
    for (const m of meshes) {
      const p = params(m);
      // the skull: r 0.15 scaled [1, 1.1, 1] (the hood is also r 0.15, scaled differently)
      if (m.geometry.type === 'SphereGeometry' && near(p.radius, 0.15) && near(m.scale.y, 1.1) && near(m.scale.x, 1) && !head) head = m.parent;
      if (m.geometry.type === 'SphereGeometry' && near(p.radius, 0.042)) hands.push(m);
    }
  }
  const holdGroups = hands.map((h) => h.parent!.children.find((c) => !(c as THREE.Mesh).isMesh && c !== h && meshesOf(c).length > 0) ?? null);
  const headInv = head ? (head as THREE.Object3D).matrixWorld.clone().invert() : null;
  const pts: Pt[] = [];
  const lp = new THREE.Vector3();
  for (const m of meshes) {
    const pos = m.geometry.getAttribute('position');
    if (!pos) continue;
    const p = params(m);
    const held = holdGroups.some((g) => g && isUnder(m, g));
    const inHead = head && isUnder(m, head);
    let part = 'body';
    if (kind === 'jake') {
      if (held) part = 'held object';
      else if (inHead) part = 'head';
      else if (m.geometry.type === 'CapsuleGeometry') part = near(p.radius, 0.068) ? 'hips/thigh' : near(p.radius, 0.058) ? 'shin' : near(p.radius, 0.155) ? 'torso' : 'arm';
      else if (hands.includes(m)) part = 'hand';
      else if (m.geometry.type === 'BoxGeometry' && mat(m)?.color?.getHexString() === 'f2f2f2') part = 'foot';
    }
    const step = Math.max(1, Math.floor(pos.count / 400));
    for (let i = 0; i < pos.count; i += step) {
      const w = new THREE.Vector3().fromBufferAttribute(pos, i).applyMatrix4(m.matrixWorld);
      let face = false;
      let pt = part;
      if (kind === 'jake' && inHead && headInv) { lp.copy(w).applyMatrix4(headInv); face = lp.z > 0.05 && lp.y > -0.13; }
      if (kind === 'hoot') {
        lp.copy(w).applyMatrix4(inv);
        face = lp.y > 1.05 && lp.y < 1.7 && lp.z > 0.3 && Math.abs(lp.x) < 0.6;
        pt = lp.y < 0.15 ? 'feet' : lp.y > 1.0 ? 'head' : 'body';
      }
      pts.push({ w, part: pt, face, mesh: m });
    }
  }
  return { pts, hands, holdGroups, head };
};

const measure3D = () => {
  const scene = Q.scene as THREE.Scene | null, cam = Q.camera as THREE.PerspectiveCamera | null;
  if (!scene || !cam) return { chars: [], held: [], furniture: [] };
  scene.updateMatrixWorld(true);
  cam.updateMatrixWorld(true);
  cam.matrixWorldInverse.copy(cam.matrixWorld).invert();
  const t = Q.committed / FPS;
  const furniture: any[] = typeof qaData.furniture === 'function' ? qaData.furniture(t) : qaData.furniture ?? [];
  const ignore: string[] = qaData.ignoreOccluders ?? [];
  // occluder candidates: opaque-ish meshes
  const occluders: THREE.Mesh[] = [];
  scene.traverse((o) => {
    const m = o as THREE.Mesh;
    if (!m.isMesh || !visibleChain(m)) return;
    const mt = mat(m);
    if (!mt || mt.visible === false) return;
    if (mt.transparent && (mt.opacity ?? 1) < 0.5) return;
    if (mt.side === THREE.BackSide) return; // sky domes, inner beak shells
    occluders.push(m);
  });
  const roots: THREE.Object3D[] = [];
  scene.traverse((o) => { if (o.userData?.qaChar && visibleChain(o)) roots.push(o); });
  const counts: Record<string, number> = {};
  const rc = new THREE.Raycaster();
  const chars: any[] = [], held: any[] = [], furn: any[] = [];
  for (const root of roots) {
    const kind = root.userData.qaChar as string;
    counts[kind] = (counts[kind] ?? 0) + 1;
    const id = counts[kind] > 1 ? `${kind}#${counts[kind]}` : kind;
    const { pts, hands, holdGroups } = characterPoints(root, kind);
    if (!pts.length) continue;
    // --- visibility via raycasts on a subsample (+ every face point up to ~150)
    const body = pts.filter((p) => !p.face), face = pts.filter((p) => p.face);
    const pick = (arr: Pt[], n: number) => { const s = Math.max(1, Math.floor(arr.length / n)); return arr.filter((_, i) => i % s === 0); };
    const sample = [...pick(body, 260), ...pick(face, 150)];
    const stat = () => ({ n: 0, onVis: 0, onOcc: 0, off: { left: 0, right: 0, top: 0, bottom: 0 } as Record<string, number>, offOcc: 0, behind: 0, occBy: {} as Record<string, number>, box: null as Box | null, ext: null as Box | null });
    const sb = stat(), sf = stat();
    for (const p of sample) {
      const st = p.face ? sf : sb;
      st.n++;
      const s = project(cam, p.w);
      if (s.behind) { st.behind++; continue; }
      const dir = p.w.clone().sub(cam.position);
      const dist = dir.length();
      rc.set(cam.position, dir.normalize());
      rc.near = cam.near; rc.far = Math.max(cam.near, dist - 0.006);
      let occ: string | null = null;
      for (const h of rc.intersectObjects(occluders, false)) {
        if (isUnder(h.object, root)) continue;
        const name = describe(h.object as THREE.Mesh, furniture);
        if (ignore.some((g) => name.includes(g))) continue;
        occ = name; break;
      }
      const on = s.x >= 0 && s.x <= W && s.y >= 0 && s.y <= H;
      if (occ) { if (on) { st.onOcc++; st.occBy[occ] = (st.occBy[occ] ?? 0) + 1; } else st.offOcc++; continue; }
      st.ext = union(st.ext, { left: s.x, top: s.y, width: 1, height: 1 });
      if (on) { st.onVis++; st.box = union(st.box, { left: s.x, top: s.y, width: 1, height: 1 }); continue; }
      const over = { left: -s.x, right: s.x - W, top: -s.y, bottom: s.y - H };
      const edge = Object.entries(over).sort((a, b) => b[1] - a[1])[0][0];
      st.off[edge]++;
    }
    const r = (b: Box | null) => (b ? { x: Math.round(b.x), y: Math.round(b.y), w: Math.round(b.w), h: Math.round(b.h) } : null);
    const pack = (s: ReturnType<typeof stat>) => ({ ...s, box: r(s.box), ext: r(s.ext) });
    chars.push({ id, kind, body: pack(sb), face: pack(sf) });

    // --- hands and held objects (gap between the hand surface and the object)
    hands.forEach((hm, i) => {
      const g = holdGroups[i];
      if (!g) return;
      const c = new THREE.Vector3().setFromMatrixPosition(hm.matrixWorld);
      const sc = new THREE.Vector3().setFromMatrixScale(hm.matrixWorld);
      const rad = 0.042 * Math.max(sc.x, sc.y, sc.z);
      let best = Infinity;
      for (const m of meshesOf(g)) {
        const pos = m.geometry.getAttribute('position');
        for (let k = 0; k < pos.count; k++) { v.fromBufferAttribute(pos, k).applyMatrix4(m.matrixWorld); best = Math.min(best, v.distanceTo(c) - rad); }
      }
      const sp = project(cam, c);
      const side = hm.parent?.parent?.position.x ?? 0;
      held.push({ id, hand: side > 0 ? 'right' : 'left', gap: +best.toFixed(4), screen: { x: Math.round(sp.x), y: Math.round(sp.y) } });
    });

    // --- body inside furniture boxes (penetration depth)
    for (const f of furniture) {
      const tol = f.tol ?? 0.02;
      const parts: Record<string, { depth: number; n: number; box: Box | null }> = {};
      for (const p of pts) {
        const w = p.w;
        if (w.x <= f.min[0] || w.x >= f.max[0] || w.y <= f.min[1] || w.y >= f.max[1] || w.z <= f.min[2] || w.z >= f.max[2]) continue;
        const d = Math.min(w.x - f.min[0], f.max[0] - w.x, w.y - f.min[1], f.max[1] - w.y, w.z - f.min[2], f.max[2] - w.z);
        if (d <= tol) continue;
        const e = (parts[p.part] ??= { depth: 0, n: 0, box: null });
        e.depth = Math.max(e.depth, d); e.n++;
        const s = project(cam, w);
        if (!s.behind) e.box = union(e.box, { left: s.x, top: s.y, width: 1, height: 1 });
      }
      for (const [part, e] of Object.entries(parts)) furn.push({ id, part, furniture: f.name, depth: +e.depth.toFixed(3), n: e.n, box: r(e.box) });
    }
  }
  return { chars, held, furniture: furn };
};

Q.measure = (with3D = true) => {
  const out: any = { frame: Q.committed, t: +(Q.committed / FPS).toFixed(3), overlays: measureOverlays() };
  if (with3D) Object.assign(out, measure3D());
  return out;
};

/** Draw annotation shapes (in frame pixels) over the frame for the screenshot. */
Q.annotate = (shapes: { x: number; y: number; w: number; h: number; color: string; width?: number; label?: string }[], header: string, bad: boolean) => {
  const el = document.getElementById('qa-annot')!;
  const svg = [`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" style="position:absolute;inset:0">`];
  svg.push(`<rect x="0" y="${H * 0.85}" width="${W}" height="${H * 0.15}" fill="rgba(255,0,0,0.06)" stroke="rgba(255,255,255,0.35)" stroke-dasharray="12 10" stroke-width="3"/>`);
  svg.push(`<line x1="${W * 0.05}" y1="0" x2="${W * 0.05}" y2="${H}" stroke="rgba(255,255,255,0.35)" stroke-dasharray="12 10" stroke-width="3"/><line x1="${W * 0.95}" y1="0" x2="${W * 0.95}" y2="${H}" stroke="rgba(255,255,255,0.35)" stroke-dasharray="12 10" stroke-width="3"/>`);
  for (const s of shapes) {
    svg.push(`<rect x="${s.x}" y="${s.y}" width="${Math.max(4, s.w)}" height="${Math.max(4, s.h)}" fill="none" stroke="${s.color}" stroke-width="${s.width ?? 4}"/>`);
    if (s.label) svg.push(`<text x="${Math.min(W - 60, Math.max(4, s.x))}" y="${Math.max(60, s.y - 10)}" font-family="Arial" font-weight="bold" font-size="54" fill="${s.color}" stroke="#000" stroke-width="3" paint-order="stroke">${s.label}</text>`);
  }
  svg.push(`<rect x="0" y="0" width="${W}" height="${H}" fill="none" stroke="${bad ? '#ff2020' : 'rgba(0,0,0,0)'}" stroke-width="${bad ? 28 : 0}"/>`);
  svg.push(`<rect x="0" y="0" width="${W}" height="110" fill="rgba(0,0,0,0.6)"/><text x="24" y="86" font-family="Arial" font-weight="bold" font-size="80" fill="${bad ? '#ff5050' : '#ffffff'}">${header}</text>`);
  svg.push('</svg>');
  el.innerHTML = svg.join('');
};
